sqlplus / as sysdba << 'EOF'
ALTER SESSION SET CONTAINER = FREEPDB1;
ALTER USER system IDENTIFIED BY "Oracle123";
ALTER USER sys IDENTIFIED BY "Oracle123";
DROP USER hotel_app CASCADE;
DROP USER hotel_owner CASCADE;
CREATE USER hotel_owner IDENTIFIED BY "HotelOwner123#" DEFAULT TABLESPACE users QUOTA UNLIMITED ON users;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE PROCEDURE, CREATE TRIGGER, CREATE JOB, CREATE VIEW, CREATE SYNONYM TO hotel_owner;
EXIT;
EOF
